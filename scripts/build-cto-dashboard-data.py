#!/usr/bin/env python3
"""Bundle CTO snapshot JSON for file:// dashboard usage."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
IN_PATH = ROOT / "data" / "cto-ops-snapshot.json"
OUT_PATH = ROOT / "dashboard" / "cto-data.js"


def main() -> None:
    if not IN_PATH.exists():
        payload = {
            "generatedAt": "",
            "summary": {
                "ociProfileCount": 0,
                "ociAuthOkCount": 0,
                "estimatedMonthlyCost": 0,
                "firewallUnexpectedPublicIngressCount": 0,
                "crowdsecMissingCount": 0,
                "heartbeatFailures": 0,
                "sesDomainFailures": 0,
            },
            "ociProfiles": [],
            "firewallFindings": [],
            "sshHosts": [],
            "heartbeat": [],
            "sesDns": [],
            "enhance": {"enabled": False},
        }
    else:
        payload = json.loads(IN_PATH.read_text(encoding="utf-8"))

    js = (
        "// Auto-generated by build-cto-dashboard-data.py\n"
        f"window.CTO_OPS_DATA = {json.dumps(payload, ensure_ascii=False)};\n"
    )
    OUT_PATH.write_text(js, encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
