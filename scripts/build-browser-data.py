#!/usr/bin/env python3
"""Build dashboard/browser-data.js so dashboard/browser.html works from file:// without fetch."""

from __future__ import annotations

import json
from pathlib import Path


def main() -> None:
    project_root = Path(__file__).resolve().parent.parent
    data_dir = project_root / "data"
    docs_dir = project_root / "docs"
    dashboard_dir = project_root / "dashboard"

    audit_json_path = data_dir / "audit-findings.json"
    vhost_plan_path = data_dir / "vhost-projects.json"
    vhost_deploy_cfg_path = data_dir / "vhost-deploy-config.json"
    todo_md_path = docs_dir / "TODO.md"
    skills_todo_md_path = docs_dir / "SKILLS-TODO.md"
    audit_md_path = docs_dir / "AUDIT.md"
    out_path = dashboard_dir / "browser-data.js"

    audit_findings = json.loads(audit_json_path.read_text(encoding="utf-8"))
    vhost_plan = (
        json.loads(vhost_plan_path.read_text(encoding="utf-8"))
        if vhost_plan_path.exists()
        else {"version": "0.5.0", "defaults": {}, "projects": []}
    )
    vhost_deploy_cfg = (
        json.loads(vhost_deploy_cfg_path.read_text(encoding="utf-8"))
        if vhost_deploy_cfg_path.exists()
        else {}
    )
    todo_md = todo_md_path.read_text(encoding="utf-8")
    skills_todo_md = (
        skills_todo_md_path.read_text(encoding="utf-8")
        if skills_todo_md_path.exists()
        else ""
    )
    audit_md = audit_md_path.read_text(encoding="utf-8")

    payload = {
        "auditFindings": audit_findings,
        "todoMd": todo_md,
        "skillsTodoMd": skills_todo_md,
        "auditMd": audit_md,
        "vhostPlan": vhost_plan,
        "vhostDeployConfig": vhost_deploy_cfg,
    }

    js = (
        "// Auto-generated by build-browser-data.py\n"
        "// Regenerate after editing data/audit-findings.json or docs/*.md.\n"
        f"window.OPENCLAW_BROWSER_DATA = {json.dumps(payload, ensure_ascii=False)};\n"
    )
    out_path.write_text(js, encoding="utf-8")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
